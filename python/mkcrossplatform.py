#!/usr/bin/env python3
"""Build tables/crossplatform.tex from the reference and cross-platform E1 sweeps.

Reviewers asked whether the latency results hold outside the single Apple M4 Mac
mini on which every number of the submitted version was produced. The same
harness, at the same commit, against the same committed seeded fixtures, was
re-run on x86-64 Linux inside a container. This script reduces the two sets of
CSVs to one comparison table and emits the LaTeX.

Nothing is re-timed here; only measured CSV rows are summarized. Rows are keyed
by (system, config, depth) at fanout 1, the configuration the article reports.

Usage: python3 mkcrossplatform.py <reference_csv_dir> <cloud_csv_dir> <out.tex>
"""

from __future__ import annotations

import csv
import glob
import os
import sys
from pathlib import Path

DEPTHS = [1, 2, 4, 6, 8, 10]

# (system, config) -> printed label, in table order.
ROWS = [
    (("biscuit", "na"), r"Biscuit (\texttt{biscuit-auth}, Rust)"),
    (("opa", "local"), r"OPA / local"),
    (("opa", "5ms"), r"OPA / $+5$\,ms"),
    (("opa", "20ms"), r"OPA / $+20$\,ms"),
]


def load(csv_dir: str) -> dict:
    """(system, config, depth) -> p50 microseconds, fanout 1 only."""
    out: dict = {}
    for path in sorted(glob.glob(os.path.join(csv_dir, "*.csv"))):
        with open(path, newline="") as f:
            for row in csv.DictReader(f):
                if row.get("schema") != "pct-eval/e1@1":
                    continue
                if int(row["fanout"]) != 1:
                    continue
                key = (row["system"], row["config"], int(row["depth"]))
                out[key] = int(row["p50_ns"]) / 1000.0
    return out


def fmt(v: float | None) -> str:
    if v is None:
        # The manuscript carries no em dashes; use an explicit marker instead.
        return r"n/a"
    if v >= 10000:
        thousands, rest = divmod(int(round(v)), 1000)
        return f"{thousands}{{,}}{rest:03d}"
    if v >= 100:
        return f"{int(round(v))}"
    return f"{v:.0f}"


def main() -> None:
    ref_dir, cloud_dir, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    ref, cloud = load(ref_dir), load(cloud_dir)

    lines = []
    ratios = []
    for (system, config), label in ROWS:
        for platform, data, plabel in (
            ("ref", ref, r"Apple M4 (reference)"),
            ("cloud", cloud, r"x86-64 container"),
        ):
            cells = []
            for d in DEPTHS:
                cells.append(fmt(data.get((system, config, d))))
            lead = label if platform == "ref" else ""
            lines.append(f"{lead} & {plabel} & " + " & ".join(cells) + r" \\")
        for d in DEPTHS:
            a, b = ref.get((system, config, d)), cloud.get((system, config, d))
            if a and b:
                ratios.append(b / a)
        lines.append(r"\addlinespace")
    if lines and lines[-1] == r"\addlinespace":
        lines.pop()

    body = "\n".join(lines)
    caption = (
        r"\textbf{Measured (this work).} E1 replicated on a second platform: "
        r"exercise-time verification latency, p50 in microseconds, by "
        r"delegation-chain depth, at fanout~1. Both rows of each pair come from "
        r"the same harness at the same commit, the same committed seeded "
        r"fixtures, the same OPA 1.18.2, and the same \texttt{toxiproxy} delay "
        r"injection; only the platform differs. Reference: Apple M4 Mac mini, "
        r"macOS/aarch64. Cross-platform: Intel Xeon at 2.10\,GHz, four vCPUs, "
        r"Linux/x86-64, inside a container under a hypervisor. "
        r"\texttt{capability-grant@1} is absent because its artifact is not "
        r"public and could not be exercised off the reference machine."
    )

    tex = (
        "% GENERATED by R2/harness/mkcrossplatform.py -- do not edit by hand.\n"
        "\\begin{table}[t]\n\\centering\n"
        f"\\caption{{{caption}}}\n"
        "\\label{tab:crossplatform}\n\\small\n"
        "\\begin{tabular}{@{}llrrrrrr@{}}\n\\toprule\n"
        "System / configuration & Platform & $d{=}1$ & $d{=}2$ & $d{=}4$ & "
        "$d{=}6$ & $d{=}8$ & $d{=}10$ \\\\\n\\midrule\n"
        f"{body}\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )

    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(tex)

    print(f"wrote {out_path}")
    if ratios:
        print(f"cloud/reference p50 ratio: min {min(ratios):.2f} "
              f"max {max(ratios):.2f} over {len(ratios)} cells")
    for (system, config), _ in ROWS:
        rs = [cloud[(system, config, d)] / ref[(system, config, d)]
              for d in DEPTHS
              if (system, config, d) in ref and (system, config, d) in cloud]
        if rs:
            print(f"  {system}/{config}: ratio min {min(rs):.2f} max {max(rs):.2f}")


if __name__ == "__main__":
    main()
